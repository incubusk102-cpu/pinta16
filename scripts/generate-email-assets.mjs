#!/usr/bin/env node
// Build-time generator for email-bound static images.
//
// Inlining the Canvas Hub C-logo and the footer social icons into the
// rendered email HTML as base64 data URIs (instead of fetching them
// from canvhub.com) sidesteps a class of "broken image" bugs caused by
// Cloudflare's bot challenge, image-proxy CORS, and short-lived TLS
// hiccups on the email client side. The asset payload is small enough
// (~20–30 KB total) that the email body still fits comfortably under
// Gmail's 102 KB clip threshold.
//
// Output: functions/api/_lib/email-assets-data.js (committed). The
// renderer in functions/api/_lib/email.js imports the named exports
// from that module and stamps them straight into the <img src=...>.
//
// Idempotent: re-running the script regenerates the same file given
// the same inputs.
//
// Run automatically by `npm run build` via the `prebuild` script.
// Run on demand with `npm run generate:email-assets`.

import { readFile, writeFile, readdir, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const PUBLIC_DIR = path.join(ROOT, "public");
const OUT_FILE = path.join(
  ROOT,
  "functions",
  "api",
  "_lib",
  "email-assets-data.js",
);

// Email displays the brand C-logo at 56×56 CSS px. 128 px PNG covers
// 2× retina without inflating the email body.
const BRAND_LOGO_EMAIL_WIDTH = 128;

// Email-specific brand mark: a clean transparent gold "C" (no rounded
// black square background). Kept separate from `public/icon-512.png`
// — which still ships the PWA/favicon variant with the dark square —
// so updating the email default doesn't change the storefront favicon.
// Admins can still upload a custom logo per template; this file is
// only used when no custom upload is set.
const BRAND_LOGO_SOURCE = "email-brand-c-logo.png";

const dataUri = (mime, bytes) =>
  `data:${mime};base64,${bytes.toString("base64")}`;

const generateBrandLogo = async () => {
  const src = path.join(PUBLIC_DIR, BRAND_LOGO_SOURCE);
  const buf = await sharp(src)
    .resize({
      width: BRAND_LOGO_EMAIL_WIDTH,
      height: BRAND_LOGO_EMAIL_WIDTH,
      fit: "contain",
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    })
    .png({ compressionLevel: 9 })
    .toBuffer();
  return dataUri("image/png", buf);
};

const generateFooterIcons = async () => {
  const dir = path.join(PUBLIC_DIR, "email-icons");
  const entries = await readdir(dir);
  const icons = {};
  for (const name of entries.sort()) {
    if (!name.endsWith(".png")) continue;
    const slug = name.replace(/\.png$/, "");
    const src = path.join(dir, name);
    const buf = await readFile(src);
    icons[slug] = dataUri("image/png", buf);
  }
  return icons;
};

// Each base64 string is far longer than Prettier's 80-char wrap, so
// Prettier won't try to break the line — it leaves `key: "value",` on
// one row regardless. We mirror that exact shape so re-running the
// generator produces a byte-stable file (no spurious diff after
// `npm run format`).
const formatModule = (brandLogo, footerIcons) => {
  const lines = [
    "// AUTO-GENERATED by scripts/generate-email-assets.mjs.",
    "// Do not edit by hand — regenerate by running",
    "//   npm run generate:email-assets",
    "// or simply `npm run build` (which runs the generator as a prebuild step).",
    "//",
    "// Why inline?  Cloudflare's bot challenge can intermittently block",
    "// email image proxies (Gmail, iCloud, Outlook …) from fetching static",
    "// assets on canvhub.com, leaving the recipient with broken-image icons.",
    "// Embedding the small brand assets as data: URIs sidesteps the issue at",
    "// the cost of ~25 KB per email — well below Gmail's 102 KB clip cap.",
    "",
    "export const DEFAULT_BRAND_LOGO_DATA_URI =",
    `  ${JSON.stringify(brandLogo)};`,
    "",
    "export const FOOTER_ICON_DATA_URIS = Object.freeze({",
  ];
  for (const [slug, uri] of Object.entries(footerIcons)) {
    lines.push(`  ${slug}: ${JSON.stringify(uri)},`);
  }
  lines.push("});");
  lines.push("");
  return lines.join("\n");
};

const main = async () => {
  await mkdir(path.dirname(OUT_FILE), { recursive: true });
  const [brandLogo, footerIcons] = await Promise.all([
    generateBrandLogo(),
    generateFooterIcons(),
  ]);
  const out = formatModule(brandLogo, footerIcons);
  await writeFile(OUT_FILE, out, "utf8");
  const sizeKb = (Buffer.byteLength(out, "utf8") / 1024).toFixed(1);
  console.log(
    `email-assets: wrote ${path.relative(ROOT, OUT_FILE)} (${sizeKb} KB, ${
      Object.keys(footerIcons).length
    } footer icons + brand logo)`,
  );
};

main().catch((err) => {
  console.error("[generate-email-assets] failed:", err);
  process.exit(1);
});
