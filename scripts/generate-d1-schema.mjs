#!/usr/bin/env node
// Build-time generator for the D1 runtime-bootstrap schema.
//
// The D1 schema is defined in `migrations/*.sql` (the source of truth
// — `wrangler d1 migrations apply` walks these files in
// lexicographic order). The admin panel can also bootstrap a fresh
// D1 instance without the wrangler CLI by hitting
// `POST /api/admin/d1?action=apply-schema`, which iterates over the
// `D1_SCHEMA_STATEMENTS` array exported from
// `functions/api/_lib/d1-schema.js` and runs each statement against
// the bound D1.
//
// Before this script existed those two paths drifted: every new
// migration had to be manually mirrored into `d1-schema.js`, and the
// header comment in `d1-schema.js` explicitly called the duplication
// out as a footgun. This generator removes that footgun by parsing
// the migration files and emitting `d1-schema.js` automatically, so
// the runtime bootstrap is always a faithful replay of what wrangler
// would apply.
//
// Output: `functions/api/_lib/d1-schema.js` (committed). Run
// automatically by `npm run build` via the `prebuild` script. Run on
// demand with `npm run generate:d1-schema`.
//
// Idempotent: re-running the script regenerates the same file given
// the same migration inputs. CI uses `--check` to fail the build if
// the committed `d1-schema.js` has drifted from `migrations/*.sql`.

import { readFile, writeFile, readdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const MIGRATIONS_DIR = path.join(ROOT, "migrations");
const OUT_FILE = path.join(ROOT, "functions", "api", "_lib", "d1-schema.js");

const CHECK_FLAG = "--check";
const isCheckMode = process.argv.includes(CHECK_FLAG);

/**
 * Strip SQL line comments (`-- …` to end of line). Our migrations use
 * line comments exclusively; if a future migration needs a block
 * comment (`/* … *\/`) extend this here.
 */
const stripComments = (sql) =>
  sql
    .split("\n")
    .map((line) => {
      const idx = line.indexOf("--");
      return idx === -1 ? line : line.slice(0, idx);
    })
    .join("\n");

/**
 * Split a SQL string on top-level `;` boundaries. Our migrations
 * don't embed semicolons inside string literals, so a naive split is
 * safe. Each yielded statement is trimmed and empty entries are
 * dropped.
 */
const splitStatements = (sql) =>
  sql
    .split(";")
    .map((stmt) => stmt.trim())
    .filter((stmt) => stmt.length > 0);

const listMigrationFiles = async () => {
  const entries = await readdir(MIGRATIONS_DIR);
  return entries
    .filter((name) => name.endsWith(".sql"))
    .sort((a, b) => a.localeCompare(b));
};

/**
 * Parse a single migration file into ordered SQL statements. Returns
 * an array of `{ migration, sql }` pairs — `migration` is the
 * filename (e.g. `0001_initial.sql`) so the emitted file can label
 * which statement came from which migration in inline comments.
 */
const parseMigration = async (filename) => {
  const raw = await readFile(path.join(MIGRATIONS_DIR, filename), "utf8");
  const stripped = stripComments(raw);
  return splitStatements(stripped).map((sql) => ({ migration: filename, sql }));
};

/**
 * Walk the migrations directory in order and concatenate every
 * statement into a single flat list. The runtime bootstrap path
 * replays this list in the same order wrangler would.
 */
const collectStatements = async () => {
  const files = await listMigrationFiles();
  const all = [];
  for (const file of files) {
    const parsed = await parseMigration(file);
    all.push(...parsed);
  }
  return all;
};

/**
 * Render the JS module. Groups statements by their source migration
 * file so a human scanning `d1-schema.js` can still see the
 * migration boundaries.
 */
const renderModule = (statements) => {
  const grouped = new Map();
  for (const { migration, sql } of statements) {
    if (!grouped.has(migration)) grouped.set(migration, []);
    grouped.get(migration).push(sql);
  }

  const lines = [
    "// d1-schema.js",
    "//",
    "// AUTO-GENERATED by `scripts/generate-d1-schema.mjs` from",
    "// `migrations/*.sql`. Do not edit by hand — your changes will be",
    "// overwritten on the next build. To change the schema, add or edit a",
    "// migration file under `migrations/` and re-run `npm run",
    "// generate:d1-schema` (the `prebuild` hook also re-runs this).",
    "//",
    "// Exposed so the admin panel can bootstrap the database from the",
    "// running app (POST /api/admin/d1?action=apply-schema) without",
    "// requiring the operator to install the wrangler CLI.",
    "//",
    "// SOURCE OF TRUTH: `migrations/*.sql`. The generator parses them in",
    "// lexicographic order — the same order `wrangler d1 migrations apply`",
    "// uses — so a fresh D1 instance bootstrapped through the admin",
    "// endpoint ends up with the same schema wrangler would produce.",
    "//",
    "// Most statements are `CREATE … IF NOT EXISTS`, so applying twice is",
    "// a no-op. Older migrations include `ALTER TABLE ADD COLUMN`",
    "// statements that are not idempotent on their own; the apply-schema",
    "// endpoint tolerates the resulting `duplicate column name` errors so",
    "// re-running this array against an already-bootstrapped D1 is safe.",
    "",
    "export const D1_SCHEMA_STATEMENTS = [",
  ];

  for (const [migration, stmts] of grouped) {
    lines.push(`  // -- ${migration} --`);
    for (const sql of stmts) {
      lines.push(`  \`${sql}\`,`);
    }
    lines.push("");
  }

  // Drop the trailing blank line before the closing bracket.
  if (lines[lines.length - 1] === "") lines.pop();
  lines.push("];", "");
  return lines.join("\n");
};

const main = async () => {
  const statements = await collectStatements();
  const next = renderModule(statements);

  if (isCheckMode) {
    let current = "";
    try {
      current = await readFile(OUT_FILE, "utf8");
    } catch (err) {
      if (err.code !== "ENOENT") throw err;
    }
    if (current !== next) {
      console.error(
        `[generate-d1-schema] ${path.relative(ROOT, OUT_FILE)} is out of date.\n` +
          "Run `npm run generate:d1-schema` and commit the result.",
      );
      process.exit(1);
    }
    return;
  }

  await writeFile(OUT_FILE, next, "utf8");
  console.log(
    `[generate-d1-schema] wrote ${statements.length} statements to ` +
      path.relative(ROOT, OUT_FILE),
  );
};

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
